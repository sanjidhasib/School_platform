const express = require('express');
const router = express.Router();
const c = require('../../controllers/admin/subjectController');
const { protect } = require('../../middleware/auth');
const { requireRole } = require('../../middleware/rbac');
const admin = [protect, requireRole('ADMIN')];
router.get('/', ...admin, c.list);
router.post('/', ...admin, c.create);
router.get('/curriculum', ...admin, c.curriculum);
router.post('/curriculum', ...admin, c.applyCurriculum);
router.patch('/:id', ...admin, c.update);
router.delete('/:id/grades/:grade', ...admin, c.removeFromGrade);
router.delete('/:id', ...admin, c.remove);
module.exports = router;
